
const { test } = require("node:test");
const assert = require("node:assert/strict");
const { randomUUID } = require("node:crypto");
const path = require("node:path");

const express = require("express");
const mongoose = require("mongoose");
const bcrypt = require("bcryptjs");

require("dotenv").config({
  path: path.join(__dirname, "../.env"),
});

const User = require("../models/User");
const MentorshipRequest = require("../models/MentorshipRequest");

const authRoutes = require("../routes/authRoutes");
const mentorRoutes = require("../routes/mentorRoutes");

// Separate database to protect the real application
const TEST_DATABASE = "student_mentorship_test";

// Integration tests require explicit permission
const runTests =
  process.env.RUN_INTEGRATION_TESTS === "yes";

test(
  "Student Mentorship Platform - Integration Tests",
  {
    skip: !runTests
      ? "Set RUN_INTEGRATION_TESTS=yes to run."
      : false,
    timeout: 180000,
  },
  async (t) => {
    assert.ok(
      process.env.MONGO_URI,
      "MONGO_URI is missing from .env"
    );

    assert.ok(
      process.env.JWT_SECRET,
      "JWT_SECRET is missing from .env"
    );

    const uniqueId = randomUUID().replace(/-/g, "");

    const studentEmail =
      `student-${uniqueId}@example.com`;

    const mentorEmail =
      `mentor-${uniqueId}@example.com`;

    const adminEmail =
      `admin-${uniqueId}@example.com`;

    const studentPassword = `Student-${randomUUID()}!`;
    const mentorPassword = `Mentor-${randomUUID()}!`;
    const adminPassword = `Admin-${randomUUID()}!`;

    let server = null;
    let baseUrl = "";
    let studentToken = "";
    let mentorToken = "";
    let adminToken = "";
    let mentorId = "";
    let requestId = "";
    let databaseConnected = false;

    const connectTestDatabase = async () => {
      await mongoose.connect(process.env.MONGO_URI, {
        dbName: TEST_DATABASE,
        serverSelectionTimeoutMS: 12000,
      });

      databaseConnected = true;

      assert.equal(
        mongoose.connection.name,
        TEST_DATABASE,
        "Refusing to use a non-test database"
      );
    };

    // Cleanup: only remove accounts and requests
    // generated by this test run.
    t.after(async () => {
      if (server) {
        await new Promise((resolve) => {
          server.close(resolve);
        });
      }

      if (databaseConnected) {
        try {
          if (mongoose.connection.readyState !== 1) {
            await connectTestDatabase();
          }

          await MentorshipRequest.deleteMany({
            studentEmail,
          });

          await User.deleteMany({
            email: {
              $in: [
                studentEmail,
                mentorEmail,
                adminEmail,
              ],
            },
          });
        } finally {
          await mongoose.disconnect();
        }
      }
    });

    // Connect to the isolated test database
    await connectTestDatabase();

    // Initialize model indexes
    await User.init();
    await MentorshipRequest.init();

    // Create a separate Express app for testing.
    // The normal backend server is not modified.
    const app = express();

    app.use(express.json());

    app.use("/api/auth", authRoutes);
    app.use("/api/mentors", mentorRoutes);

    app.get("/", (req, res) => {
      res.json({
        message: "Test API running",
      });
    });

    // Start on a random available port
    server = app.listen(0, "127.0.0.1");

    await new Promise((resolve, reject) => {
      if (server.listening) {
        resolve();
      } else {
        server.once("listening", resolve);
        server.once("error", reject);
      }
    });

    baseUrl =
      `http://127.0.0.1:${server.address().port}`;

    // Helper for sending API requests
    const api = async (
      endpoint,
      { method = "GET", token, body } = {}
    ) => {
      const headers = {};

      if (token) {
        headers.Authorization = `Bearer ${token}`;
      }

      if (body !== undefined) {
        headers["Content-Type"] = "application/json";
      }

      const response = await fetch(
        `${baseUrl}${endpoint}`,
        {
          method,
          headers,
          body:
            body !== undefined
              ? JSON.stringify(body)
              : undefined,
        }
      );

      const text = await response.text();

      return {
        status: response.status,
        body: text ? JSON.parse(text) : null,
      };
    };

    // ========================================
    // TEST 1 - PREVENT PUBLIC ADMIN REGISTRATION
    // ========================================

    await t.test(
      "Public registration cannot create admin accounts",
      async () => {
        const result = await api("/api/auth/register", {
          method: "POST",
          body: {
            name: "Unauthorized Admin",
            email: adminEmail,
            password: adminPassword,
            role: "admin",
          },
        });

        assert.equal(result.status, 400);

        const admin = await User.findOne({
          email: adminEmail,
        });

        assert.equal(admin, null);
      }
    );

    // ========================================
    // TEST 2 - REGISTER STUDENT AND MENTOR
    // ========================================

    await t.test(
      "Student and mentor registration",
      async () => {
        const student = await api("/api/auth/register", {
          method: "POST",
          body: {
            name: "Test Student",
            email: studentEmail,
            password: studentPassword,
            role: "student",
            university: "University of Ruhuna",
            department: "Technology",
          },
        });

        assert.equal(student.status, 201);
        assert.equal(student.body.user.role, "student");

        studentToken = student.body.token;

        const mentor = await api("/api/auth/register", {
          method: "POST",
          body: {
            name: "Test Mentor",
            email: mentorEmail,
            password: mentorPassword,
            role: "mentor",
            university: "University of Ruhuna",
            department: "Computer Science",
          },
        });

        assert.equal(mentor.status, 201);
        assert.equal(mentor.body.user.role, "mentor");

        mentorToken = mentor.body.token;
        mentorId = mentor.body.user.id;

        assert.ok(studentToken);
        assert.ok(mentorToken);
        assert.ok(mentorId);

        // Verify database persistence
        const savedStudent = await User.findOne({
          email: studentEmail,
        });

        const savedMentor = await User.findOne({
          email: mentorEmail,
        });

        assert.ok(savedStudent);
        assert.ok(savedMentor);
      }
    );

    // ========================================
    // TEST 3 - LOGIN
    // ========================================

    await t.test(
      "Login and password authentication",
      async () => {
        const login = await api("/api/auth/login", {
          method: "POST",
          body: {
            email: studentEmail,
            password: studentPassword,
          },
        });

        assert.equal(login.status, 200);
        assert.ok(login.body.token);

        const wrongPassword = await api(
          "/api/auth/login",
          {
            method: "POST",
            body: {
              email: studentEmail,
              password: "IncorrectPassword123!",
            },
          }
        );

        assert.equal(wrongPassword.status, 401);
      }
    );

    // ========================================
    // TEST 4 - AUTHORIZATION
    // ========================================

    await t.test(
      "Protected APIs require a valid JWT",
      async () => {
        const response = await api(
          "/api/mentors/requests"
        );

        assert.equal(response.status, 401);
      }
    );

    // ========================================
    // TEST 5 - PROFILE UPDATE
    // ========================================

    await t.test(
      "Mentor profile updates persist in MongoDB",
      async () => {
        const response = await api(
          "/api/auth/profile",
          {
            method: "PATCH",
            token: mentorToken,
            body: {
              name: "Updated Test Mentor",
              university: "University of Ruhuna",
              department: "Computer Science",
              expertise: "React, Node.js",
              availability: "Monday 4 PM - 6 PM",
              bio: "Experienced development mentor.",
            },
          }
        );

        assert.equal(response.status, 200);

        const savedMentor = await User.findById(
          mentorId
        );

        assert.equal(
          savedMentor.expertise,
          "React, Node.js"
        );

        assert.equal(
          savedMentor.availability,
          "Monday 4 PM - 6 PM"
        );

        assert.equal(
          savedMentor.bio,
          "Experienced development mentor."
        );
      }
    );

    // ========================================
    // TEST 6 - ROLE RESTRICTION
    // ========================================

    await t.test(
      "Students cannot change their role or mentor fields",
      async () => {
        const response = await api(
          "/api/auth/profile",
          {
            method: "PATCH",
            token: studentToken,
            body: {
              role: "admin",
              expertise: "Unauthorized expertise",
            },
          }
        );

        assert.equal(response.status, 200);

        const student = await User.findOne({
          email: studentEmail,
        });

        assert.equal(student.role, "student");
        assert.equal(student.expertise, "");
      }
    );

    // ========================================
    // TEST 7 - DYNAMIC MENTOR DIRECTORY
    // ========================================

    await t.test(
      "Registered mentors appear in directory",
      async () => {
        const response = await api("/api/mentors");

        assert.equal(response.status, 200);

        const mentor = response.body.find(
          (item) => item.id === mentorId
        );

        assert.ok(mentor);

        assert.equal(
          mentor.expertise,
          "React, Node.js"
        );

        assert.equal(
          mentor.bio,
          "Experienced development mentor."
        );
      }
    );

    // ========================================
    // TEST 8 - CREATE MENTORSHIP REQUEST
    // ========================================

    await t.test(
      "Students can create mentorship requests",
      async () => {
        const response = await api(
          "/api/mentors/request",
          {
            method: "POST",
            token: studentToken,
            body: {
              mentorId,
              message: "I need academic guidance.",
            },
          }
        );

        assert.equal(response.status, 201);

        requestId = response.body.request.id;

        assert.ok(requestId);

        const savedRequest =
          await MentorshipRequest.findOne({
            id: requestId,
          });

        assert.ok(savedRequest);
        assert.equal(savedRequest.status, "pending");
      }
    );

    // ========================================
    // TEST 9 - STUDENT CANNOT APPROVE
    // ========================================

    await t.test(
      "Students cannot approve mentorship requests",
      async () => {
        const response = await api(
          `/api/mentors/requests/${requestId}/status`,
          {
            method: "PATCH",
            token: studentToken,
            body: {
              status: "approved",
            },
          }
        );

        assert.equal(response.status, 403);
      }
    );

    // ========================================
    // TEST 10 - MENTOR APPROVAL
    // ========================================

    await t.test(
      "Mentor can approve assigned requests",
      async () => {
        const response = await api(
          `/api/mentors/requests/${requestId}/status`,
          {
            method: "PATCH",
            token: mentorToken,
            body: {
              status: "approved",
            },
          }
        );

        assert.equal(response.status, 200);

        const savedRequest =
          await MentorshipRequest.findOne({
            id: requestId,
          });

        assert.equal(
          savedRequest.status,
          "approved"
        );
      }
    );

    // ========================================
    // TEST 11 - ADMIN PERMISSIONS
    // ========================================

    await t.test(
      "Admin can log in and view requests",
      async () => {
        // Create a test-only administrator
        const hashedPassword = await bcrypt.hash(
          adminPassword,
          12
        );

        await User.create({
          name: "Test Platform Admin",
          email: adminEmail,
          password: hashedPassword,
          role: "admin",
          university: "Platform",
          department: "Administration",
        });

        const login = await api("/api/auth/login", {
          method: "POST",
          body: {
            email: adminEmail,
            password: adminPassword,
          },
        });

        assert.equal(login.status, 200);
        assert.equal(login.body.user.role, "admin");

        adminToken = login.body.token;

        const response = await api(
          "/api/mentors/requests",
          {
            token: adminToken,
          }
        );

        assert.equal(response.status, 200);

        assert.ok(
          response.body.some(
            (request) => request.id === requestId
          )
        );
      }
    );

    // ========================================
    // TEST 12 - DATABASE PERSISTENCE
    // ========================================

    await t.test(
      "Records survive database reconnection",
      async () => {
        // Disconnect the test database
        await mongoose.disconnect();

        // Reconnect to exactly the same test DB
        await connectTestDatabase();

        const savedRequest =
          await MentorshipRequest.findOne({
            id: requestId,
          });

        assert.ok(savedRequest);

        assert.equal(
          savedRequest.status,
          "approved"
        );

        const savedMentor = await User.findById(
          mentorId
        );

        assert.ok(savedMentor);

        assert.equal(
          savedMentor.expertise,
          "React, Node.js"
        );

        // Verify through API as well
        const response = await api(
          "/api/mentors/requests",
          {
            token: studentToken,
          }
        );

        assert.equal(response.status, 200);

        assert.ok(
          response.body.some(
            (request) =>
              request.id === requestId &&
              request.status === "approved"
          )
        );
      }
    );

    // ========================================
    // TEST 13 - DELETE PERMISSION
    // ========================================

    await t.test(
      "Approved requests cannot be deleted",
      async () => {
        const response = await api(
          `/api/mentors/requests/${requestId}`,
          {
            method: "DELETE",
            token: studentToken,
          }
        );

        assert.equal(response.status, 400);
      }
    );

    console.log(
      "\nIntegration tests completed against:",
      TEST_DATABASE
    );
  }
);
